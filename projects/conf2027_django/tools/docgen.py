def check_anchors(text):
    """Все ссылки вида (#раздел) должны вести в существующий заголовок.

    Правило повторяет то, как Markdown-рендереры делают якорь из
    заголовка: нижний регистр, пробелы в дефисы, пунктуация отброшена,
    буквы любого алфавита сохранены.
    """
    import re

    def slug(title):
        out = []
        for ch in title.strip().lower():
            if ch.isalnum():
                out.append(ch)
            elif ch.isspace() or ch == "-":
                out.append("-")
        return re.sub(r"-+", "-", "".join(out)).strip("-")

    heads = {slug(h) for h in re.findall(r"^## (.+)$", text, re.MULTILINE)}
    links = set(re.findall(r"\]\(#([^)]+)\)", text))
    return sorted(links - heads)


