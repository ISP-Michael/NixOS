def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8").rstrip("\n")


def block(rel, note=None, drop=None, upto=None):
    """Блок кода из настоящего файла проекта."""
    text = read(rel)
    lines = text.split("\n")
    if drop:
        kept = [ln for ln in lines if not any(d in ln for d in drop)]
        lines = kept
    if upto:
        out = []
        for ln in lines:
            out.append(ln)
            if upto in ln:
                break
        lines = out
    text = "\n".join(lines)
    lang = LANG.get(pathlib.Path(rel).suffix, "")
    head = f"{note}\n\n" if note else ""
    # Завершающий перевод строки обязателен: иначе два соседних блока
    # склеятся и дадут четыре обратные кавычки вместо двух fence-ов.
    return f"{head}```{lang}\n{text}\n```\n"


def part(title):
    return f"\n## {title}\n\n"


def count(rel):
    """Сколько строк в файле или во всей папке."""
    path = ROOT / rel
    if path.is_dir():
        total = 0
        for f in sorted(path.rglob("*")):
            if f.is_file() and f.suffix in LANG:
                total += count(f.relative_to(ROOT).as_posix())
        return total
    if not path.exists():
        return None
    return len(path.read_text(encoding="utf-8").split("\n")) - 1


def filemap(rows):
    """Таблица «файл — строк — зачем» с числами из настоящих файлов."""
    out = ["| Файл | Строк | Зачем |", "|---|---|---|"]
    for rel, note in rows:
        n = count(rel)
        label = f"`{rel}`" if not rel.endswith("/") else f"`{rel}*`"
        out.append(f"| {label} | {'—' if n is None else n} | {note} |")
    return "\n".join(out) + "\n"


