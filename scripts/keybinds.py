#!/usr/bin/env python3
"""Generate docs/keybinds.md from user/dotfiles/.config/hypr/binds/*.lua.

Run without arguments to rewrite the document; --check verifies that the
committed table is up to date (used by make check).
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BINDS = ROOT / "user/dotfiles/.config/hypr/binds"
OUT = ROOT / "docs/keybinds.md"

SECTIONS = [
    ("apps.lua", "Приложения"),
    ("windows.lua", "Окна"),
    ("workspaces.lua", "Столы"),
    ("zoom.lua", "Масштаб"),
    ("hardware-keys.lua", "Железные клавиши"),
]

# Substring in the Lua action -> human label. Order matters: specific first.
LABELS = [
    ("exec_cmd(P.commands.wallpaper .. ' close')", "закрыть выбор обоев"),
    ("exec_cmd(P.commands.wallpaper)", "выбор обоев"),
    ("exec_cmd(P.commands.windowMenu)", "переключатель окон (rofi)"),
    ("exec_cmd(P.commands.menu)", "меню приложений (rofi)"),
    ("exec_cmd(P.terminal)", "терминал (kitty)"),
    ("exec_cmd(P.fileManager)", "файловый менеджер"),
    ("exec_cmd(P.commands.colorPicker)", "пипетка цвета"),
    ("exec_cmd(P.commands.clipboard)", "буфер обмена (CopyQ)"),
    ("brightnessctl s +1%", "яркость +"),
    ("brightnessctl s 1%-", "яркость −"),
    ("pamixer -i 5", "громкость +"),
    ("pamixer -d 5", "громкость −"),
    ("pamixer -t", "mute"),
    ("window.close", "закрыть окно"),
    ("window.float", "плавающее окно"),
    ("window.fullscreen", "полный экран"),
    ("window.pseudo", "pseudo-tiling"),
    ("group.toggle", "группа окон"),
    ("into_group", "добавить в группу"),
    ("out_of_group", "вынуть из группы"),
    ("window.resize", "ресайз окна"),
    ("window.drag", "переместить окно"),
    ("cycle(1)", "следующее окно"),
    ("cycle(-1)", "предыдущее окно"),
    ("toggle_special", "special:magic"),
    ("workspace = 'special:magic'", "окно на special:magic"),
    ("workspace = 'e+1'", "следующий пустой стол"),
    ("workspace = 'e-1'", "предыдущий пустой стол"),
    ("window.move", "окно на стол 1…10"),
    ("focus", "стол 1…10"),
    ("zoom(1)", "масштаб +"),
    ("zoom(-1)", "масштаб −"),
]

KEY_NAMES = {
    "left": "←",
    "right": "→",
    "up": "↑",
    "down": "↓",
    "comma": ",",
    "period": ".",
    "equal": "=",
    "minus": "-",
    "mouse:272": "ЛКМ",
    "mouse:273": "ПКМ",
    "mouse_down": "колесо ↓",
    "mouse_up": "колесо ↑",
}


def read_blocks(text: str):
    """Yield argument lists of top-level hl.bind(...) calls."""
    pos = 0
    while True:
        match = re.search(r"hl\.bind\s*\(", text[pos:])
        if not match:
            return
        start = pos + match.end()
        depth = 1
        args: list[list[str]] = [[]]
        i = start
        quote = ""
        while i < len(text) and depth:
            ch = text[i]
            if quote:
                args[-1].append(ch)
                if ch == quote and text[i - 1] != "\\":
                    quote = ""
            elif ch in "'\"":
                quote = ch
                args[-1].append(ch)
            elif ch in "([{":
                depth += 1
                args[-1].append(ch)
            elif ch in ")]}":
                depth -= 1
                if depth:
                    args[-1].append(ch)
            elif ch == "," and depth == 1:
                args.append([])
            else:
                args[-1].append(ch)
            i += 1
        pos = i
        yield ["".join(part).strip() for part in args]


def combo(expr: str) -> str:
    expr = (
        expr.replace("P.mainMod", '"SUPER"')
        .replace("P.alt", '"ALT"')
        .replace("P.ctrl", '"CTRL"')
    )
    expr = expr.replace("key", "1…0")
    expr = re.sub(r"\bi\b", "1…0", expr)
    strings = re.findall(r"'([^']*)'|\"([^\"]*)\"", expr)
    if strings:
        text = "".join(left or right for left, right in strings).strip()
    else:
        text = expr.strip()
    if "1…0" in expr and "1…0" not in text:
        text = (text + " 1…0").strip()
    parts = [KEY_NAMES.get(part.strip(), part.strip()) for part in text.split(" + ")]
    return " + ".join(parts)


def label(action: str) -> str:
    flat = " ".join(action.split())
    for needle, text in LABELS:
        if needle in flat:
            return text
    return flat


def render() -> str:
    lines = [
        "# Горячие клавиши Hyprland",
        "",
        "<!-- generated by scripts/keybinds.py; do not edit by hand -->",
        "",
        "`mainMod = SUPER`, `alt = ALT`, `ctrl = CTRL` (`lib/defaults.lua`).",
        "`1…0` — клавиши 1–0 (десятый стол).",
        "Таблица собрана из `user/dotfiles/.config/hypr/binds/`; после правки",
        "биндов выполни `make keybinds`.",
        "",
    ]

    seen: set[tuple[str, str]] = set()
    for filename, title in SECTIONS:
        path = BINDS / filename
        if not path.exists():
            continue
        rows = []
        for args in read_blocks(path.read_text(encoding="utf-8")):
            if len(args) < 2:
                continue
            keys = combo(args[0])
            action = label(args[1])
            if not keys or (keys, action) in seen:
                continue
            seen.add((keys, action))
            rows.append((keys, action))
        if not rows:
            continue
        lines += [f"## {title}", "", "| Клавиши | Действие |", "|---|---|"]
        for keys, action in rows:
            lines.append(f"| `{keys}` | {action} |")
        lines.append("")

    lines += [
        "Клавиши яркости и звука работают и на локскрине (`locked = true`), с",
        "повтором при удержании. Слои keyd (Alt, цифры, навигация) —",
        "`docs/keyd.md`.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/keybinds.md is stale; run make keybinds", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
