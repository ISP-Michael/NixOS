#!/usr/bin/env bash
# smooth-scroll.sh — плавная прокрутка колесом в tmux (copy-mode).
#
# Запускается из tmux.conf на каждый тик колеса:
#   smooth-scroll.sh up|down <pane_id> [строк за тик] [пауза между строками, с]
# Вместо одного прыжка на N строк прокручивает их по одной с маленькими паузами —
# движение получается плавным. Своя плавность kitty (pixel_scroll) сюда не попадает:
# когда мышь забрало приложение (tmux), прокручивает только оно само.
#
# Вся анимация — одной цепочкой команд в одном клиенте tmux, а паузы между
# строками — серверные таймеры «run-shell -d» (без процессов и без sleep).
# Тик занимает ~30 мс вместо ~70 мс, кадры идут в 2–3 раза чаще.
#
# Настройка «под себя»: третий и четвёртый аргументы (по умолчанию 3 строки, 6 мс;
# 6 мс — кадр как repaint_delay у kitty).

set -u

dir=${1:-}
pane=${2:-}
lines=${3:-3}
step=${4:-0.006}

[[ $dir == up || $dir == down ]] || exit 1
[[ $pane == %* ]] || exit 1
[[ $lines =~ ^[0-9]+$ ]] || exit 1
(( lines > 0 )) || exit 0

args=(send-keys -t "$pane" -X "scroll-$dir")
for ((i = 1; i < lines; i++)); do
    args+=( ';' run-shell -d "$step" ';' send-keys -t "$pane" -X "scroll-$dir" )
done

# Если панель дошла до края и copy-mode уже закрылся — команды молча не сработают.
tmux "${args[@]}" 2>/dev/null || exit 0

# Важно: код выхода обязан быть 0. При ненулевом tmux печатает на панель
# "'<команда>' returned N" и переводит её в view-mode.
exit 0
